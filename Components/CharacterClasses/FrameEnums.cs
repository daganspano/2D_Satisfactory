namespace _2D_Satisfactory.Components.CharacterClasses;

/// <summary>
/// Defines enumerations for animation frames and direction frames used in character animations.
/// </summary>
public enum AnimationFrame
{
    Running1 = 0,
    Stationary = 1,
    Running2 = 2,
}

/// <summary>
/// Defines enumerations for direction frames used in character animations, representing the four cardinal directions.
/// </summary>
public enum DirectionFrame
{
    Down = 0,
    Left = 1,
    Right = 2,
    Up = 3,
}