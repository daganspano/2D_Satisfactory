    /// <summary>
    /// Determines whether a given hitbox (represented as a Rectangle) is colliding with any iron ore deposit tiles on the map. This method iterates through the map's tile data and checks for intersections between the hitbox and the rectangles representing iron ore deposit tiles. If a collision is detected, the method returns true; otherwise, it returns false.
    /// </summary>
    /// <param name="hitBox">The hitbox to check for collisions with iron ore deposit tiles.</param>
    /// <returns>True if the hitbox is colliding with any iron ore deposit tiles; otherwise, false.</returns>
    public static bool IsCollidingWithIronOreDeposit(Rectangle hitBox)
    {
        for (int y = 0; y < MapSize.Y; y++)
        {
            for (int x = 0; x < MapSize.X; x++)
            {
                if (Tiles[y][x] == 4)
                {
                    Rectangle tileRectangle = new Rectangle(x * TileSize.X, y * TileSize.Y, TileSize.X, TileSize.Y);
                    if (hitBox.Intersects(tileRectangle))
                    {
                        return true;
                    }
                }
            }
        }
        return false;
    }
