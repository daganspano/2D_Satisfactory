    public static bool IsCollidingWithIronOreDeposit(Rectangle hitBox)
    {
        for (int y = 0; y < MapSize.Y; y++)
        {
            for (int x = 0; x < MapSize.X; x++)
            {
                if (Tiles[y][x] == 4)
                {
                    Rectangle tileRectangle = new Rectangle(x * TileSize.X, y * TileSize.Y, TileSize.X, TileSize.Y);
                    if (hitBox.Intersects(tileRectangle))
                    {
                        return true;
                    }
                }
            }
        }
        return false;
    }
